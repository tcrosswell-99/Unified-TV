#!/usr/bin/env python3
"""Assemble the Unified TV Frame web app into an UNSIGNED .wgt (a zip). Python standard library only.

The result, samsung/out/UnifiedTV-Frame-unsigned.wgt, is a development and CI artefact. It is not signed and will not
install on a retail Samsung TV as it is: signing needs the owner's own Samsung author and distributor certificates,
applied with Tizen Studio's `tizen package` on the owner's computer (samsung/README.md). This script never reads,
creates or expects any certificate. The staged folder samsung/out/UnifiedTV-Frame/ is what the owner signs.

Run from anywhere: python3 samsung/tools/package.py
"""
import hashlib
import json
import os
import re
import shutil
import struct
import sys
import xml.etree.ElementTree as ET
import zipfile
import zlib
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]          # samsung/
REPO = HERE.parent
OUT = HERE / "out"
STAGE = OUT / "UnifiedTV-Frame"
WGT = OUT / "UnifiedTV-Frame-unsigned.wgt"
PRIVILEGES = {
    "http://tizen.org/privilege/internet",
    "http://tizen.org/privilege/tv.inputdevice",
    "http://tizen.org/privilege/application.launch",
    "http://tizen.org/privilege/application.info",
}
FIXED_TIME = (2026, 10, 25, 0, 0, 0)   # reproducible zip entries


def fail(message):
    print("package: " + message, file=sys.stderr)
    sys.exit(1)


def png(width, height, pixel):
    """A plain RGB PNG built from pixel(x, y) -> (r, g, b)."""
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            rows.extend(pixel(x, y))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b""))


def icon():
    """An original icon: a dark field with a soft violet light and a white rounded bar (a dock). 512 x 423, Samsung's TV size."""
    w, h = 512, 423

    def pixel(x, y):
        dx, dy = (x - 256) / 256.0, (y - 190) / 211.0
        glow = max(0.0, 1.0 - (dx * dx + dy * dy) ** 0.5)
        r, g, b = 12 + 120 * glow, 14 + 60 * glow, 30 + 170 * glow
        if 120 <= x <= 392 and 290 <= y <= 330:
            edge = min(x - 120, 392 - x, y - 290, 330 - y)
            if edge >= 0:
                r = g = b = 235
        return (int(min(255, r)), int(min(255, g)), int(min(255, b)))

    return png(w, h, pixel)


def check_config(path):
    try:
        root = ET.parse(path).getroot()
    except ET.ParseError as e:
        fail(f"config.xml is not valid XML: {e}")
    ns = {"t": "http://tizen.org/ns/widgets"}
    found = {p.get("name") for p in root.findall("t:privilege", ns)}
    if found != PRIVILEGES:
        fail(f"config.xml privileges {sorted(found)} differ from the documented set {sorted(PRIVILEGES)}")
    app = root.find("t:application", ns)
    if app is None or not re.fullmatch(r"[0-9A-Za-z]{10}", app.get("package", "")):
        fail("config.xml needs a 10-character package id")


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    STAGE.mkdir(parents=True)
    check_config(HERE / "config.xml")
    shutil.copy2(HERE / "config.xml", STAGE / "config.xml")
    shutil.copytree(HERE / "src", STAGE, dirs_exist_ok=True)

    # Palettes as a script, so the page needs no file request at start-up. palettes.json stays the one source.
    palettes = json.loads((HERE / "src" / "palettes.json").read_text(encoding="utf-8"))
    (STAGE / "js" / "palettes.data.js").write_text(
        "/* Generated by samsung/tools/package.py from palettes.json. Do not edit. */\n"
        "window.UTV_PALETTE_DATA = " + json.dumps(palettes, separators=(",", ":")) + ";\n", encoding="utf-8")
    (STAGE / "icon.png").write_bytes(icon())

    # Wallpaper artwork: copied from images already in the repository, with their credits.
    sources = json.loads((HERE / "wallpaper.json").read_text(encoding="utf-8"))["pictures"]
    catalogue = []
    (STAGE / "wallpaper").mkdir(exist_ok=True)
    for pic in sources:
        source = REPO / pic["from"]
        if not source.is_file():
            print(f"package: skipping missing artwork {pic['from']}")
            continue
        shutil.copy2(source, STAGE / pic["file"])
        catalogue.append({"file": pic["file"], "title": pic["title"], "credit": pic["credit"]})
    (STAGE / "wallpaper" / "catalogue.json").write_text(json.dumps(catalogue, indent=2) + "\n", encoding="utf-8")
    (STAGE / "js" / "wallpaper.data.js").write_text(
        "/* Generated by samsung/tools/package.py from samsung/wallpaper.json. Do not edit. */\n"
        "window.UTV_WALLPAPER_DATA = " + json.dumps(catalogue, separators=(",", ":")) + ";\n", encoding="utf-8")

    # Nothing that looks like a signature or a key may be packaged.
    for path in STAGE.rglob("*"):
        name = path.name.lower()
        if name in ("author-signature.xml",) or re.fullmatch(r"signature\d*\.xml", name) or path.suffix.lower() in (".p12", ".pfx", ".pem", ".key", ".jks"):
            fail(f"refusing to package signing material: {path.relative_to(STAGE)}")

    # Every script and stylesheet the page names must exist (the webapis script is supplied by the TV itself).
    html = (STAGE / "index.html").read_text(encoding="utf-8")
    for ref in re.findall(r'(?:src|href)="([^"$:#]+)"', html):
        if not (STAGE / ref).is_file():
            fail(f"index.html refers to {ref}, which is not in the package")

    files = sorted(p for p in STAGE.rglob("*") if p.is_file())
    with zipfile.ZipFile(WGT, "w", zipfile.ZIP_DEFLATED) as z:
        for path in files:
            info = zipfile.ZipInfo(path.relative_to(STAGE).as_posix(), FIXED_TIME)
            info.compress_type = zipfile.ZIP_STORED if path.suffix.lower() in (".jpg", ".png") else zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, path.read_bytes())

    digest = hashlib.sha256(WGT.read_bytes()).hexdigest()
    (OUT / "SHA256SUMS.txt").write_text(f"{digest}  {WGT.name}\n", encoding="utf-8")
    version = ET.parse(HERE / "config.xml").getroot().get("version")
    (OUT / "manifest.txt").write_text(
        "Unified TV for Samsung Frame: UNSIGNED development package (test only)\n"
        f"version: {version}\nfiles: {len(files)}\nartwork: {len(catalogue)}\nsha256: {digest}\n"
        "status: implemented_unverified; not installed or tested on the Frame\n"
        "signing: none. The owner signs samsung/out/UnifiedTV-Frame/ with their own Samsung certificates (samsung/README.md)\n",
        encoding="utf-8")
    print(f"package: {WGT.relative_to(REPO)} ({WGT.stat().st_size // 1024} KB, {len(files)} files, sha256 {digest[:16]}...)")


if __name__ == "__main__":
    main()
